"""Write the references of the skill in `skill/rowih/references/` from the canonical data
and the reference specification: the grammar summary and the lexicon listing, which
`rowih.summary` generates, and the specification's chapter on the notation, with each
link to a file outside the skill reduced to its text. `tests/test_skill.py` holds the
written files to what this writes. Run from the repository root:
`python3 tools/build_skill.py`."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))

from rowih import data, summary  # noqa: E402

SKILL = os.path.join(ROOT, "skill", "rowih")
LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
GENERATED_MARK = re.compile(r"^<!-- (?:generated: [a-z-]+|end generated) -->\n", re.M)
HEADER = ("<!-- Generated by tools/build_skill.py from %s; edit the source, not this "
          "file. -->\n\n")


def _within(text: str) -> str:
    """The text with each link that leaves the file reduced to its words, a chapter's
    title in italics: the skill carries this chapter alone, and an anchor within it is
    kept."""
    def reduce(m):
        words, target = m.group(1), m.group(2)
        if target.startswith("#"):
            return m.group(0)
        return words if words.startswith("`") else "*%s*" % words
    return LINK.sub(reduce, text)


def references() -> dict:
    """Each reference's path within the skill, and its text."""
    lang = data.load()
    with open(os.path.join(ROOT, "specification", "notation.md"), encoding="utf-8") as f:
        notation = GENERATED_MARK.sub("", _within(f.read()))
    return {
        "references/grammar.md": HEADER % "the language's data" + summary.grammar(lang),
        "references/lexicon.md": HEADER % "the lexicon's data" + summary.lexicon(lang),
        "references/notation.md": HEADER % "specification/notation.md" + notation,
    }


def main():
    for path, text in references().items():
        target = os.path.join(SKILL, path)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, "w", encoding="utf-8") as f:
            f.write(text)
        print("%s: %d words" % (path, len(text.split())))


if __name__ == "__main__":
    main()
