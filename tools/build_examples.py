"""Write the examples the public page shows, in `examples/`, from the corpus: for each
message of each exchange chosen below, its drawing in the native writing as the toolchain
renders it, the drawing of its moves alone with a version for a dark page, the PNG of
the opening exchange, and `examples/README.md`, which gives each message's
transliteration, morpheme gloss, literal semantic form and English explanation as the
toolchain writes them. It also writes `examples/speech.json`, the phonemes of each line as
the spoken form states them, from which `tools/speak_examples.py` writes the audio. For the
page's account of the writing system it draws the nineteen components from their pen
strokes and the language's name as a word.

The page draws each move it shows in rows, each with the transliteration of exactly that
row's words beneath it, and this writes those rows into the page's regions marked
`<!-- rows: MESSAGE FORM -->` ... `<!-- end rows -->`: the two moves of the opening
exchange, the moves of three messages chosen for what their drawings show, and the opening
question in the compact and handwritten forms. A move is one line, and the writing system
states no rule for breaking a line, so the rows are a view: they break only between words,
never inside a run of numerals, which shares one frame, nor between two walls, and each is
laid out by the toolchain's own line layout, so that a unit opened on one row and closed on
a later one is drawn as a side whose unit is not closed on its line.

`tests/test_examples.py` holds every file to what this writes. Run from the repository
root: `python3 tools/build_examples.py`."""
import json
import os
import re
import sys
from html import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from gloss_corpus import record  # noqa: E402
from rowih import api, data, drawing, render, writing  # noqa: E402
from rowih.drawing import draw  # noqa: E402
from rowih.generator import morpheme_gloss  # noqa: E402
from rowih.speech import spoken  # noqa: E402

EXAMPLES = os.path.join(ROOT, "examples")
MEDIA = "media"
OPENING = "casual-056"
# (corpus set, item, heading): the opening exchange, then one exchange of each kind the
# page names, and the adversarial message the page's case cites
EXCHANGES = [
    ("domains", OPENING, "A question and its answer"),
    ("domains", "delegation-098", "A delegation"),
    ("domains", "negotiation-098", "A negotiation"),
    ("domains", "correction-100", "A correction"),
    ("domains", "humour-077", "A joke"),
    ("adversarial", "a03-quoted-instruction", "An instruction inside a quotation"),
]
# (corpus set, message): the narrowest move of the corpus drawing a number in its frame, a
# quotation between walls, and the ceremonial variant, found by a search on 2026-10-24
WRITING = [("domains", "evidence-011.1"), ("domains", "metalinguistic-001.1"),
           ("domains", "metalinguistic-047.1")]
# (corpus set, message, forms): each move the page draws in rows
ROWS = [("domains", OPENING + ".1", drawing.FORMS), ("domains", OPENING + ".2", ("display",))] + \
    [(corpus_set, name, ("display",)) for corpus_set, name in WRITING]
# a row is drawn at SCALE pixels to a lattice unit, at which a component is 18 pixels tall,
# and is no wider than ROW_LIMIT units, 780 pixels, where a break allows: GitHub shows a
# README in a column of about 830 pixels and shrinks a wider image to fit
SCALE, ROW_LIMIT = 1.5, 520
ROW_REGION = re.compile(r"(?P<head><!-- rows: (?P<name>[a-z0-9.-]+) (?P<form>[a-z]+) -->\n\n)"
                        r".*?(?P<tail>\n\n<!-- end rows -->)", re.S)
NAME = "rowih"
# the chart of components, in lattice units: a cell for each symbol, a row for each kind
CELL, ROW, MARGIN, LETTER_SIZE, SOUND_SIZE = 28, 44, 8, 8, 7
# the voice of Kokoro-82M that speaks for each participant (tools/speak_examples.py)
VOICES = {"1": "em_alex", "2": "ef_dora"}
DARK_INK = "#e6edf3"
SIZE = re.compile(r'viewBox="0 0 (\d+) (\d+)" width="\d+" height="\d+"')
HEADER = ("<!-- Generated by tools/build_examples.py from the corpus; edit the tool, not "
          "this file. -->\n\n")


def _source(corpus_set: str, item: str) -> dict:
    with open(os.path.join(ROOT, "corpus", "source", corpus_set + ".json"),
              encoding="utf-8") as f:
        return next(x for x in json.load(f)["items"] if x["id"] == item)


def _text(corpus_set: str, name: str) -> str:
    with open(os.path.join(ROOT, "corpus", corpus_set, name + ".txt"), encoding="utf-8") as f:
        return f.read()


def dark(svg: str) -> str:
    """The drawing in a light ink, for a dark page: the toolchain draws in the page's
    current colour, which an image does not inherit."""
    return svg.replace('="currentColor"', '="%s"' % DARK_INK)


def moves_only(svg: str, analysis, lang) -> str:
    """The drawing cropped to its move lines by its view box, every stroke unchanged:
    each line occupies the band from its offset less the metric `above`."""
    d = draw(analysis, "display", lang)
    top = d.lines[1] - lang.writing["metrics"]["above"]
    right = max([x for p in d.paths if min(y for _, y in p.points) >= top
                 for x, _ in p.points] + [t.x + t.width for t in d.texts if t.y >= top])
    width, height = right + lang.writing["metrics"]["margin"], d.height - top
    alt = "\n".join(" ".join(w.form for w in words) for words in analysis.message.lines)
    full = _text_of(analysis)
    out = SIZE.sub('viewBox="0 %d %d %d" width="%d" height="%d"'
                   % (top, width, height, width, height), svg, count=1)
    return out.replace(full, alt + "\n", 2)


def _text_of(analysis) -> str:
    lines = [analysis.message.envelope.words] + list(analysis.message.lines)
    return "".join(" ".join(w.form for w in words) + "\n" for words in lines)


def media(name: str, text: str, lang) -> dict:
    """Each file of one message's drawings, by its path within `examples/`."""
    a = api.parse(text)
    if a.diagnostics:
        raise ValueError("%s draws %s" % (name, [x.code for x in a.diagnostics]))
    svg, _ = api.render(text, "svg")
    crop = moves_only(svg, a, lang)
    out = {"%s/%s.svg" % (MEDIA, name): svg, "%s/%s.moves.svg" % (MEDIA, name): crop,
           "%s/%s.moves.dark.svg" % (MEDIA, name): dark(crop)}
    if name.startswith(OPENING):
        out["%s/%s.png" % (MEDIA, name)] = api.render(text, "png")[0]
    return out


def _is_numeral(word, lang) -> bool:
    return word.item is not None and word.item.class_id == lang.writing["numbers"]["class"]


def breakable(words: list, i: int, lang) -> bool:
    """Whether a row may end before word i: not inside a run of numerals, nor between two
    walls."""
    if _is_numeral(words[i - 1], lang) and _is_numeral(words[i], lang):
        return False
    walls = lang.writing["walls"]
    ident = [w.item.identifier if w.item is not None else "" for w in words[:i]]
    return ident.count(walls["opens"]) == ident.count(walls["closes"])


def row_drawing(words: list, lang, form: str = "display",
                ceremonial: bool = False) -> drawing.Drawing:
    """A run of a move's words laid out by the toolchain as one line, as `draw` lays out
    each line of a message. The drawing module keeps its line layout private, and this
    applies it to part of a line."""
    line = drawing._Line(lang, ceremonial, False)
    drawing._write(line, words, form == "handwritten")
    width, above, below = line.finish()
    m = lang.writing["metrics"]
    d = drawing.Drawing(
        form, width, above + below,
        [drawing.Path(tuple((x, y + above) for x, y in p.points), p.weight)
         for p in line.paths],
        [drawing.Text(t.x, t.y + above, t.width, t.size, t.text) for t in line.texts],
        m["stroke"], m["hairline"], [above])
    return drawing._halve(d) if form == "compact" else d


def rows(words: list, lang) -> list:
    """The move's words in the fewest rows no wider than ROW_LIMIT in the display form,
    breaking only where `breakable` allows, and of those the rows whose widths are most
    even, by the least sum of their squares; a run with no break inside it may exceed the
    limit alone. For a move of n words, at most the protocol's maximum of a message, this
    lays out O(n²) runs, each in O(n)."""
    n = len(words)
    points = [0] + [i for i in range(1, n) if breakable(words, i, lang)] + [n]
    # best[b]: (rows, sum of squared widths, start of the last row) for words[:b]
    best = {0: (0, 0, None)}
    for j, b in enumerate(points[1:], 1):
        options = []
        for a in points[:j]:
            width = row_drawing(words[a:b], lang).width
            if width <= ROW_LIMIT or a == points[j - 1]:
                count, cost, _ = best[a]
                options.append((count + 1, cost + width * width, a))
        best[b] = min(options)
    out, b = [], n
    while b:
        a = best[b][2]
        out.append(words[a:b])
        b = a
    return out[::-1]


def _move(name: str, lang) -> tuple:
    """The words of a message's one move, and whether the move is ceremonial."""
    corpus_set = next(s for s, n, _ in ROWS if n == name)
    a = api.parse(_text(corpus_set, name))
    if a.diagnostics or len(a.message.lines) != 1:
        raise ValueError("%s is not one move without a diagnostic" % name)
    registers = drawing._registers(a)
    return list(a.message.lines[0]), registers.get(0) == drawing.CEREMONIAL


def row_path(name: str, k: int, form: str) -> str:
    return "%s/%s.row%d%s.svg" % (MEDIA, name, k, "" if form == "display" else "." + form)


def row_svg(d: drawing.Drawing, words: list) -> str:
    """One row as the toolchain's SVG, its text alternative the row's transliteration,
    shown at SCALE pixels to a unit."""
    svg = render._svg(d, escape(" ".join(w.form for w in words)), "normal")
    return SIZE.sub('viewBox="0 0 %d %d" width="%d" height="%d"'
                    % (d.width, d.height, round(d.width * SCALE), round(d.height * SCALE)),
                    svg, count=1)


def row_media(lang) -> dict:
    """Each row of each move the page draws in rows, in each of its forms, with a version
    for a dark page."""
    out = {}
    for _, name, forms in ROWS:
        words, ceremonial = _move(name, lang)
        for form in forms:
            for k, row in enumerate(rows(words, lang), 1):
                svg = row_svg(row_drawing(row, lang, form, ceremonial), row)
                out[row_path(name, k, form)] = svg
                out[row_path(name, k, form)[:-len(".svg")] + ".dark.svg"] = dark(svg)
    return out


def rows_markdown(name: str, form: str, lang) -> str:
    """The rows of a move as the page shows them: each drawing, with the transliteration
    of its words beneath it."""
    words, _ = _move(name, lang)
    split = rows(words, lang)
    kind = "the native writing" if form == "display" else "the %s form" % form
    return "\n\n".join(
        picture("examples/" + row_path(name, k, form),
                "Row %d of %d in %s" % (k, len(split), kind))
        + "<br>\n`%s`" % " ".join(w.form for w in row)
        for k, row in enumerate(split, 1))


def page(text: str, lang) -> str:
    """The text of the page with each region of rows written again."""
    def fill(m):
        if not any(n == m["name"] and m["form"] in f for _, n, f in ROWS):
            raise ValueError("the page draws %s %s, which ROWS lacks" % (m["name"], m["form"]))
        return m["head"] + rows_markdown(m["name"], m["form"], lang) + m["tail"]
    return ROW_REGION.sub(fill, text)


def _polylines(strokes: list, dx: int, dy: int) -> list:
    return ['<polyline points="%s"/>' % " ".join("%d,%d" % (x + dx, y + dy) for x, y in pen)
            for pen in strokes]


def _svg(width: int, height: int, alt: str, body: list, lang) -> str:
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" '
            'height="%d" role="img" aria-label="%s"><title>%s</title>'
            '<g fill="none" stroke="currentColor" stroke-width="%s" stroke-linecap="round" '
            'stroke-linejoin="round">%s</g>%s</svg>\n'
            % (width, height, width * 2, height * 2, alt, alt, lang.writing["metrics"]["stroke"],
               "".join(b for b in body if b.startswith("<polyline")),
               "".join(b for b in body if not b.startswith("<polyline"))))


def components(lang) -> str:
    """The nineteen components, each over its letter and its sound in the IPA, drawn from
    the pen strokes of `language/writing.json`, consonants on the first row."""
    symbols = lang.phonology["symbols"]
    rows = [[s for s in symbols if s["kind"] == kind] for kind in ("consonant", "vowel")]
    body = []
    for r, row in enumerate(rows):
        for i, s in enumerate(row):
            x, y = MARGIN + i * CELL + (CELL - 12) // 2, MARGIN + r * ROW
            body += _polylines(writing.pen_strokes(s["letter"], lang), x, y)
            body.append('<text x="%d" y="%d" font-size="%d" text-anchor="middle" '
                        'fill="currentColor" font-family="monospace">%s</text>'
                        % (x + 6, y + 24, LETTER_SIZE, s["letter"]))
            body.append('<text x="%d" y="%d" font-size="%d" text-anchor="middle" '
                        'fill="currentColor" font-family="serif">/%s/</text>'
                        % (x + 6, y + 33, SOUND_SIZE, s["ipa"]))
    width = 2 * MARGIN + CELL * max(len(row) for row in rows)
    alt = "The nineteen components of the writing system, with their letters and sounds"
    return _svg(width, 2 * MARGIN + ROW * len(rows) - 6, alt, body, lang)


def word(form: str, lang) -> str:
    """A word drawn as its components left to right, each in its own box of twelve units,
    with the metric `gap` between them."""
    step = 12 + lang.writing["metrics"]["gap"]
    body = [line for i, ch in enumerate(form)
            for line in _polylines(writing.pen_strokes(ch, lang), MARGIN + i * step, MARGIN)]
    return _svg(2 * MARGIN + step * len(form) - lang.writing["metrics"]["gap"], 12 + 2 * MARGIN,
                form, body, lang)


def writing_media(lang) -> dict:
    """The drawings of the page's account of the writing system."""
    out = {}
    for name, svg in (("components", components(lang)), (NAME, word(NAME, lang))):
        out["%s/%s.svg" % (MEDIA, name)] = svg
        out["%s/%s.dark.svg" % (MEDIA, name)] = dark(svg)
    out.update(row_media(lang))
    return out


def plan(name: str, text: str, sender: str) -> dict:
    """The spoken form of one message: each line's prosody and phonemes, and its voice."""
    a = api.parse(text)
    return {"sender": sender, "voice": VOICES[sender],
            "lines": [{"prosody": line["prosody"], "ipa": line["ipa"]} for line in spoken(a)]}


def picture(path: str, alt: str) -> str:
    """A drawing that follows the reader's colour scheme on GitHub."""
    stem = path[:-len(".svg")]
    return ('<picture><source media="(prefers-color-scheme: dark)" srcset="%s.dark.svg">'
            '<img src="%s.svg" alt="%s"></picture>' % (stem, stem, alt))


def message_section(k: int, name: str, text: str, message: dict, lang) -> str:
    """One message: its drawing, its links, and its layers as the toolchain writes them."""
    a = api.parse(text)
    rec = record(text)
    to = ", ".join("agent %d" % r for r in message["recipients"])
    out = ["### %d. Agent %d to %s\n" % (k, message["sender"], to),
           picture("%s/%s.moves.svg" % (MEDIA, name),
                   "The moves of message %d in the native writing" % k) + "\n",
           "[The whole message drawn](%s/%s.svg) · [Spoken (MP3)](%s/%s.mp3)\n"
           % (MEDIA, name, MEDIA, name),
           "The transliteration, the envelope on the first line and each move on a line "
           "of its own:\n", "```text\n%s```\n" % text, "The morpheme gloss:\n"]
    gloss = ["ENVELOPE  " + " ".join(morpheme_gloss(w, lang)
                                     for w in a.message.envelope.words)]
    gloss += ["MOVE %-4d " % (i + 1) + m["morpheme gloss"] for i, m in enumerate(rec["moves"])]
    out.append("```text\n%s\n```\n" % "\n".join(gloss))
    out.append("The literal semantic form:\n")
    out.append("```text\n%s\n```\n" % "\n".join(m["literal semantic form"]
                                                 for m in rec["moves"]))
    english = " ".join(m["natural English"] for m in rec["moves"])
    out.append("The English explanation: *%s*\n" % english)
    return "\n".join(out)


def readme(lang) -> str:
    """The text of `examples/README.md`."""
    out = [HEADER + "# Examples\n",
           "Each exchange below is an item of the corpus, written by the toolchain from the "
           "notation and checked by it. For each message the drawing shows its moves in the "
           "native writing, cropped from the toolchain's drawing of the whole message, which "
           "the first link opens; the second link is the message spoken. The transliteration "
           "is what models exchange. The morpheme gloss names every word, the envelope's "
           "included; the literal semantic form is the move's normal form; and the English "
           "explanation is a view made by the receiver, never sent and not the language.\n",
           "The audio is synthesised by Kokoro-82M from the phonemes of each line, agent 1 in "
           "the voice `em_alex` and agent 2 in `ef_dora`, and each file is checked against "
           "its message's phonemes by a phoneme recogniser, with the results in "
           "[`audio.json`](audio.json) (see [`tools/speak_examples.py`](../tools/"
           "speak_examples.py)). The recordings do not follow the prosody of the spoken "
           "form, which the toolchain's own synthesiser applies (`rowih speak`) and which "
           "carries no meaning.\n"]
    for corpus_set, item, heading in EXCHANGES:
        source = _source(corpus_set, item)
        statement = source["statement"][0].upper() + source["statement"][1:]
        out.append("## %s\n" % heading)
        out.append("*%s.* Item `%s` of [`corpus/%s/`](../corpus/%s/).\n"
                   % (statement.rstrip("."), item, corpus_set, corpus_set))
        for k, message in enumerate(source["messages"], 1):
            name = "%s.%d" % (item, k)
            out.append(message_section(k, name, _text(corpus_set, name), message, lang))
    return "\n".join(out)


def files() -> dict:
    """Every file this writes, by its path within `examples/`: text, or bytes."""
    lang = data.load()
    out, speech = {}, {}
    for corpus_set, item, _ in EXCHANGES:
        for k, message in enumerate(_source(corpus_set, item)["messages"], 1):
            name = "%s.%d" % (item, k)
            text = _text(corpus_set, name)
            out.update(media(name, text, lang))
            speech[name] = plan(name, text, str(message["sender"]))
    out.update(writing_media(lang))
    out["speech.json"] = json.dumps(speech, ensure_ascii=False, indent=1) + "\n"
    out["README.md"] = readme(lang)
    return out


def main():
    written = files()
    for path, content in written.items():
        target = os.path.join(EXAMPLES, path)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        mode = "wb" if isinstance(content, bytes) else "w"
        with open(target, mode, **({} if mode == "wb" else {"encoding": "utf-8"})) as f:
            f.write(content)
        print("%s: %d bytes" % (path, len(content)))
    media_dir = os.path.join(EXAMPLES, MEDIA)
    for stale in sorted(set(os.listdir(media_dir)) - {p.split("/", 1)[1] for p in written
                                                       if p.startswith(MEDIA + "/")}):
        if not stale.endswith(".mp3"):
            os.remove(os.path.join(media_dir, stale))
            print("%s/%s: removed" % (MEDIA, stale))
    readme = os.path.join(ROOT, "README.md")
    with open(readme, encoding="utf-8") as f:
        text = f.read()
    with open(readme, "w", encoding="utf-8") as f:
        f.write(page(text, data.load()))
    print("README.md: rows written in %d regions" % len(ROW_REGION.findall(text)))


if __name__ == "__main__":
    main()
