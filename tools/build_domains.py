"""The domain corpus of version 1.0: 100 items in each of the twelve domains, generated
from schemas over curated vocabulary, so that what an item says is a sensible thing for
agents to say, and written into `corpus/source/domains.json` for `tools/build_corpus.py`
to build like any other set. Each schema draws its words through a picker that takes the
least-used fitting word at every slot, so that the vocabulary spreads over the lexicon,
and the build reports every root no item uses. The domains' schemas are in the package
`tools/domains/`.

Deterministic: the same lexicon and the same schemas give the same items."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import version1_source as V  # noqa: E402
import domains  # noqa: E402
from domains import DOMAINS  # noqa: E402
from domains.compose import Picker  # noqa: E402


def build() -> tuple:
    picker = Picker()
    items = []
    for domain in DOMAINS:
        for n, (statement, messages, authored) in enumerate(domains.items(domain, picker)):
            item = {"id": "%s-%03d" % (domain.SLUG, n + 1), "domain": domain.NAME,
                    "statement": statement, "messages": messages}
            if authored:
                item["authored"] = True
            items.append(item)
    return items, picker


def main():
    items, picker = build()
    roots = [r[0] for r in V.ROOTS]
    with open(os.path.join(ROOT, "corpus", "source", "domains.json"), "w",
              encoding="utf-8") as f:
        json.dump({"note": "generated by tools/build_domains.py; do not edit by hand",
                   "items": items}, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("domains: %d items in %d domains; %d of the %d roots of lexicon 1.0 not yet drawn"
          % (len(items), len(DOMAINS), sum(1 for r in roots if not picker.used[r]),
             len(roots)))


if __name__ == "__main__":
    main()
